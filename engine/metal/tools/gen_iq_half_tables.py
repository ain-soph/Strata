#!/usr/bin/env python3
"""Generate the half-precision grid and sign-mask tables of kernels/moeh.metal (between the GENERATED markers).

The IQ2_S / IQ3_S grids hold small unsigned integers (IQ2_S {8, 25, 43}, IQ3_S {1..15}), exact in half.  moeh.metal reads
them already converted: iq2s_grid_h[i] = the 8 bytes of iq2s_grid[i] as 8 halves (uint4 = 4 half2), iq3s_grid_h[i] = the 4
bytes of iq3s_grid[i] as 4 halves (uint2), and ksign_h[s] = the sign bits of byte s as 8 half sign masks (uint4, bit 15 of
each half), so that one XOR applies the signs of two weights.  Values from the engine's own quant header (the same source
as the constant grids the other kernels read).

usage: gen_iq_half_tables.py [--check]       rewrites kernels/moeh.metal in place (--check: exit 1 if it would change)
"""
import re
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
HDR = HERE.parents[1] / "include/strata/quant/strata-quant-common.h"
MSL = HERE.parent / "kernels/moeh.metal"
BEGIN, END = "// ---- GENERATED by tools/gen_iq_half_tables.py: do not edit ----", "// ---- END GENERATED ----"


def table(src, name):
    m = re.search(r"GGML_TABLE_BEGIN\(\s*\w+\s*,\s*%s\s*,\s*[^)]+\)(.*?)GGML_TABLE_END\(\)" % name, src, re.S)
    return [int(v, 0) for v in re.findall(r"0x[0-9a-fA-F]+|\b\d+\b", m.group(1))]


def h(v):
    return struct.unpack("<H", struct.pack("<e", float(v)))[0]


def pair(a, b):
    return a | (b << 16)


def fmt(name, ty, rows):
    lines = [f"constant {ty} {name}[{len(rows)}] = {{"]
    per = 2 if ty == "uint4" else 4
    for i in range(0, len(rows), per):
        lines.append("    " + " ".join(f"{ty}({', '.join('0x%08x' % w for w in r)})," for r in rows[i:i + per]))
    lines.append("};")
    return "\n".join(lines)


def main():
    src = HDR.read_text()
    g2 = table(src, "iq2s_grid")
    g3 = table(src, "iq3s_grid")
    assert len(g2) == 1024 and len(g3) == 512, (len(g2), len(g3))
    r2 = []
    for v in g2:
        b = [(v >> (8 * k)) & 255 for k in range(8)]
        r2.append([pair(h(b[2 * k]), h(b[2 * k + 1])) for k in range(4)])
    r3 = []
    for v in g3:
        b = [(v >> (8 * k)) & 255 for k in range(4)]
        r3.append([pair(h(b[0]), h(b[1])), pair(h(b[2]), h(b[3]))])
    rs = []
    for s in range(256):
        m = [0x8000 if (s >> k) & 1 else 0 for k in range(8)]
        rs.append([pair(m[2 * k], m[2 * k + 1]) for k in range(4)])
    gen = "\n".join([BEGIN, fmt("iq2s_grid_h", "uint4", r2), fmt("iq3s_grid_h", "uint2", r3), fmt("ksign_h", "uint4", rs), END])
    text = MSL.read_text()
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: gen, text, flags=re.S)
    if "--check" in sys.argv:
        sys.exit(0 if new == text else 1)
    MSL.write_text(new)


if __name__ == "__main__":
    main()
